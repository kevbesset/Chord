"""Lists the ids of Chromium's branded strings (the ones that name the product), from
the headers grit generates, as `IDS_X,` lines for a C++ array.

Usage: branded_string_ids.py <output.inc> <header.h>...
"""

import re
import sys


def main(output, headers):
    ids = []
    for header in headers:
        with open(header, encoding='utf-8') as f:
            ids += re.findall(r'^#define (IDS_[A-Z0-9_]+) \d+$', f.read(), re.M)
    with open(output, 'w', encoding='utf-8') as f:
        f.write('// Generated by chord/tools/branded_string_ids.py. Do not edit.\n')
        f.writelines(f'{name},\n' for name in sorted(set(ids)))


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2:])
